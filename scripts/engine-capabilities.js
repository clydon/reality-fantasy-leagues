// The capability tracker (docs/PLAN-start-a-game-gpt.md step A5): writes docs/ENGINE-CAPABILITIES.md from
// tests/fixtures/engine-capabilities.json, each row's status worked out from the engine (game-spec capabilities.js statusOf:
// a spec plays now when specProblems, with its page's ctx, and specWaitsFor have nothing against it). Every engine step runs it
// and commits the result, so the git history of the doc is the engine's progress. No database, no server.
//
//   node scripts/engine-capabilities.js           write the doc
//   node scripts/engine-capabilities.js --check   exit 1 if the doc isn't what the tracker and the engine say now
//
// A page's `rulebook` is the rules its specs are checked against (src/lib/game/capability-rows.ts pageCtx): a built-in, one of
// tests/fixtures/rulebook-samples.js, or a stand-in of the same kind (`checkedAs`); every row with a spec names one.
const fs = require("fs");
const path = require("path");
const jiti = require("jiti")(__filename, { alias: { "@": path.join(__dirname, "..", "src") } });
const G = require("../src/lib/game/game-spec/index.js");
const C = require("../src/lib/game/game-spec/capabilities.js");
const { pageCtx: ctxOf, pageName } = jiti("../src/lib/game/capability-rows.ts");

const TRACKER = path.join(__dirname, "..", "tests", "fixtures", "engine-capabilities.json");
const DOC = path.join(__dirname, "..", "docs", "ENGINE-CAPABILITIES.md");
/** A stand-in's show, by its rulebook key, for "checked against The Amazing Race's rules". */
const SHOWS = { survivor: "Survivor", traitors: "The Traitors", challenge: "The Challenge", belowDeck: "Below Deck", pluribus: "Pluribus", snl: "Saturday Night Live", formula1: "Formula 1", amazingRace: "The Amazing Race" };
/** A table cell: no pipes or line breaks. */
const cell = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\s*\n\s*/g, " ").trim();

/** Each row's status, and what the doc says it needs (or, playing now, what it plays as). */
function statusRows(tracker) {
  return C.rowsOf(tracker).map((row) => {
    const ctx = ctxOf(row.page);
    const st = C.statusOf(row, ctx);
    let needs;
    if (st.state === "yes") {
      needs = G.describeSpec(row.spec, { ...(ctx || {}), show: pageName(row.page) || "this show" }).sentence;
      if (row.page && row.page.checkedAs) needs += ` (Checked against ${SHOWS[row.page.rulebook] || row.page.rulebook}'s rules, a show of its kind.)`;
    }
    else if (st.state === "step") needs = `${st.step}${row.note ? `: ${row.note}` : ""}`;
    else if (st.state === "decide") needs = row.decide;
    else if (st.state === "gpt") needs = row.note || "";
    else needs = row.note || "not planned";
    return { row, st, needs };
  });
}

/** The doc, from the tracker as the engine reads it now. Deterministic: the same tracker and engine write the same text. */
function render(tracker, all = statusRows(tracker)) {
  const count = (state) => all.filter((x) => x.st.state === state).length;
  const steps = C.STEPS.map((s) => [s, all.filter((x) => x.st.state === "step" && x.st.step === s).length]).filter(([, n]) => n);
  const mark = (x) => C.MARKS[x.st.state];
  const out = [];
  out.push("# What the engine can make");
  out.push("");
  out.push("Generated by `node scripts/engine-capabilities.js` from `tests/fixtures/engine-capabilities.json`");
  out.push("([PLAN-start-a-game-gpt.md](PLAN-start-a-game-gpt.md), step A5). Don't edit it by hand: change the tracker or the engine and");
  out.push("run it again. Every engine step does, so this file's history is the engine's progress.");
  out.push("");
  out.push(`Each status is worked out from the engine: ${["yes", "step", "new", "decide", "gpt"].map((s) => `${C.MARKS[s]} ${C.WORDS[s]}`).join(" · ")}.`);
  out.push("A row plays now when its spec passes the validator (`specProblems`, with what its page's show can settle) and nothing it");
  out.push("needs waits (`specWaitsFor`); it then says the game in the engine's own words (`describeSpec`). A show the tracker has no");
  out.push("rules for is checked against a show of its kind, and says so.");
  out.push("");
  out.push(`**Now:** ${["yes", "step", "new", "decide", "gpt"].map((s) => `${count(s)} ${C.MARKS[s]}`).join(" · ")}, of ${all.length}.`);
  out.push(`**Waiting, by step:** ${steps.map(([s, n]) => `${s} ${n}`).join(" · ")}.`);
  out.push("");
  out.push("## The dials");
  out.push("");
  out.push("Every watch-along game is a setting on these dials (the plan's \"Where the engine is headed\").");
  for (const d of tracker.dials) {
    out.push("");
    out.push(`### ${d.name}`);
    out.push("");
    out.push("| | What | Plays as, or needs |");
    out.push("|---|---|---|");
    for (const v of d.values) {
      const x = all.find((y) => y.row.id === v.id);
      out.push(`| ${mark(x)} | ${cell(v.what)} | ${cell(x.needs)} |`);
    }
  }
  const requestTable = (title, intro, rows, withDials) => {
    out.push("");
    out.push(`## ${title}`);
    out.push("");
    out.push(intro);
    out.push("");
    out.push(withDials ? "| | Id | On the page of | They type | Dials | Plays as, or needs |" : "| | Id | On the page of | They type | Plays as, or needs |");
    out.push(withDials ? "|---|---|---|---|---|---|" : "|---|---|---|---|---|");
    for (const r of rows) {
      const x = all.find((y) => y.row.id === r.id);
      const cells = [mark(x), r.id, cell(pageName(r.page)), cell(r.words), ...(withDials ? [cell((r.dials || []).join(", "))] : []), cell(x.needs)];
      out.push(`| ${cells.join(" | ")} |`);
    }
  };
  requestTable("Requests from a show's page", "The plan's worked examples, as people would type them on a show's page.", tracker.examples, true);
  requestTable("The stretch requests", "Requests that push the dials, from fantasy leagues, beyond them, and live with the watch along.", tracker.stretch, true);
  requestTable(
    "The words corpus",
    "Start a game's eval set (the playtest lane's P2, 2026-10-28), each request now typed on a page. Its expected readings stay in the tracker for G1's bank and the recorder.",
    tracker.corpus.requests,
    false
  );
  out.push("");
  return out.join("\n");
}

function main() {
  const tracker = JSON.parse(fs.readFileSync(TRACKER, "utf8"));
  const problems = C.rowsOf(tracker).flatMap((r) => C.rowProblems(r));
  if (problems.length) {
    console.error(problems.join("\n"));
    process.exit(1);
  }
  const all = statusRows(tracker);
  const text = render(tracker, all);
  if (process.argv.includes("--check")) {
    const now = fs.existsSync(DOC) ? fs.readFileSync(DOC, "utf8").replace(/\r\n/g, "\n") : "";
    if (now !== text) {
      console.error("docs/ENGINE-CAPABILITIES.md is out of date: run node scripts/engine-capabilities.js");
      process.exit(1);
    }
    console.log("docs/ENGINE-CAPABILITIES.md is up to date");
    return;
  }
  fs.writeFileSync(DOC, text, "utf8");
  console.log(`wrote docs/ENGINE-CAPABILITIES.md: ${Object.entries(C.MARKS).map(([s, m]) => `${all.filter((x) => x.st.state === s).length} ${m}`).join(" · ")}`);
}

if (require.main === module) main();

module.exports = { render, statusRows, ctxOf, pageName, TRACKER, DOC };
